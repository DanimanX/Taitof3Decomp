/* ROM 0x0D2D44 */
static int sub_0D2D44(const f3mem_t *m, uint16_t d0w, uint16_t d1w,
                      uint32_t *out_d0, uint32_t *out_d1)
{
    if (d1w > 50u)
        return -1;
    uint32_t off = (uint32_t)(int32_t)(int16_t)d0w * 4u;
    uint32_t d0 = rd32(m, 0x000D2D64u + off);
    uint32_t d1 = rd32(m, 0x000D2ECCu + off);
    *out_d0 = (uint32_t)(d0 * (uint32_t)d1w);
    *out_d1 = (uint32_t)(d1 * (uint32_t)d1w);
    return 0;
}

/* ROM 0x0E5C2A */
int Obj_E5C2A_Tick(const f3mem_t *m, uint32_t obj)
{
    int16_t idx = (int16_t)rd16(m, obj + 0x10u);
    uint32_t a3 = 0x000E5D9Eu + (uint32_t)((int32_t)idx * 8);

    sub_0CEC4C(m, obj, rd32(m, a3));
    a3 += 4u;
    wr8(m, obj + 0x07u, (uint8_t)(rd8(m, obj + 0x07u) | 0x10u));
    wr8(m, obj + 0x34u, (uint8_t)(rd8(m, obj + 0x34u) & (uint8_t)~0x02u));
    sub_0CFA86(m, obj, rd32(m, a3));

    uint16_t spd = (uint16_t)(rd16(m, obj + 0x60u) + (Obj_Next4Way(m) & 0x0003u));
    wr16(m, obj + 0x60u, spd);

    int16_t ang = (int16_t)(uint16_t)((Obj_Next4Way(m) & 0x003Fu) - 0x0020u + rd16(m, obj + 0x58u));
    if (ang < 0)
        ang = (int16_t)(ang + 0x0168);
    else if (ang >= 0x0168)
        ang = (int16_t)(ang - 0x0168);

    uint32_t vx, vy;
    if (sub_0D2D44(m, (uint16_t)ang, spd, &vx, &vy) < 0)
        return -1;
    wr32(m, obj + 0x50u, vx);
    wr32(m, obj + 0x54u, vy);

    uint32_t scroll = rd32(m, F3_A5 + 0x4224u);
    wr32(m, obj + 0x3Au, rd32(m, obj + 0x3Au) - scroll);
    wr32(m, obj + 0x14u, rd32(m, obj + 0x14u) - scroll);

    Obj_DrawSprite(m, obj);
    wr8(m, obj + 0x34u, (uint8_t)(rd8(m, obj + 0x34u) | 0x04u));
    wr32(m, obj + 0x00u, 0x000E5CBCu);
    return 0;
}
