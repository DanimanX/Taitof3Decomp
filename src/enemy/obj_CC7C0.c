/* ROM 0x0CD3D6: switch to the follow-up record 0x0CD444[D0] (optional
 * sound word first), restart animation, next state 0x0CD412 */
static void next_record(const f3mem_t *m, uint32_t obj, uint16_t d0)
{
    uint32_t a1 = rd32(m, 0x000CD444u + (uint32_t)(int32_t)(int16_t)d0 * 4u);
    uint16_t snd = rd16(m, a1); a1 += 2u;
    if (snd != 0u)
        play_sound(m, snd);
    wr32(m, obj + 0x0Cu, a1);
    wr16(m, obj + 0x3Au, 0u);
    wr16(m, obj + 0x3Eu, 0u);
    wr16(m, obj + 0x1Eu, 0u);
    wr16(m, obj + 0x1Cu, 0u);
    wr32(m, obj + 0x00u, 0x000CD412u);
}

/* ROM 0x0CC7C0: spinning shot (sprite table 0x0CC8C4) */
int Obj_CC7C0_Tick(const f3mem_t *m, uint32_t obj)
{
    if ((rd8(m, F3_A5 - 0x144Bu) & 0x10u) != 0u || (int32_t)rd32(m, obj + 0x24u) <= 0) {
        next_record(m, obj, 1u);
        return 0;
    }
    if ((rd8(m, F3_A5 + 0x1D58u) & 0x02u) != 0u) {
        int16_t x = (int16_t)rd16(m, obj + 0x14u);
        if (x >= -0x0A && x <= 0x11C) {
            /* 0x0CBB42 */
            wr8(m, obj + 0x32u, 0x0Bu);
            wr32(m, obj + 0x0Cu, 0x000CC8C4u);
            sub_0CBB2C_tail(m, obj);
            return 0;
        }
    }
    wr16(m, obj + 0x42u, (uint16_t)((int16_t)rd16(m, obj + 0x06u) >> 1));
    /* 0x0CC8A8 */
    Obj_MoveByAngle(m, obj, rd16(m, obj + 0x20u));
    {
        uint32_t a1 = rd32(m, F3_A5 + 0x906u);
        wr32(m, a1, obj);
        wr32(m, F3_A5 + 0x906u, a1 + 4u);
    }
    Obj_DrawSprite(m, obj);
    int16_t t = (int16_t)(rd16(m, obj + 0x06u) - 1u);
    wr16(m, obj + 0x06u, (uint16_t)t);
    if (t > 0) {
        wr32(m, obj + 0x00u, 0x000CC7C0u);
        return 0;
    }
    {
        int16_t x = (int16_t)rd16(m, obj + 0x14u), y = (int16_t)rd16(m, obj + 0x18u);
        if (x < (int16_t)rd16(m, 0x000CC112u) ||
            y < (int16_t)rd16(m, 0x000CC116u) || y > (int16_t)rd16(m, 0x000CC118u)) {
            Obj_Free(m, obj);
            return 0;
        }
    }
    t = (int16_t)(rd16(m, obj + 0x3Au) - 1u);
    wr16(m, obj + 0x3Au, (uint16_t)t);
    if (t <= 0) {
        next_record(m, obj, 1u);
        return 0;
    }
    wr16(m, obj + 0x42u, 2u);
    wr16(m, obj + 0x20u, 0x00A0u);
    wr16(m, obj + 0x1Eu, 0x8080u);
    wr32(m, obj + 0x10u, 0x00062D98u);
    wr16(m, obj + 0x14u, (uint16_t)(rd16(m, obj + 0x14u) + 4u));
    wr16(m, obj + 0x18u, (uint16_t)(rd16(m, obj + 0x18u) + 4u));
    wr16(m, obj + 0x06u, 0x0010u);
    wr32(m, obj + 0x00u, 0x000CC860u);
    return 0;
}
